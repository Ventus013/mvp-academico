const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
test('cadastro, edição, associação, persistência e exclusão pela interface', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#product-count')).not.toHaveText('—');
  await page.getByLabel('Código SKU').fill('BROWSER-CUBE');
  await page.getByLabel('Nome do produto').fill('Cubo do navegador');
  await page.getByLabel('Descrição opcional').fill('Um objeto de demonstração');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  const product = page.locator('#product-rows tr').filter({ hasText: 'BROWSER-CUBE' });
  await expect(product).toBeVisible();
  await product.getByRole('button', { name: 'Editar', exact: true }).click();
  await page.getByLabel('Nome do produto').fill('Cubo revisado');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  await expect(product).toContainText('Cubo revisado');
  await page.getByRole('button', { name: 'Processos', exact: true }).click();
  await page.getByLabel('Código do processo').fill('BROWSER-CHECK');
  await page.getByLabel('Nome do processo').fill('Conferência visual');
  await page.getByRole('button', { name: 'Salvar processo', exact: true }).click();
  const process = page.locator('#process-rows tr').filter({ hasText: 'BROWSER-CHECK' });
  await expect(process).toBeVisible();
  await process.getByRole('button', { name: 'Editar', exact: true }).click();
  await page.getByLabel('Nome do processo').fill('Conferência revisada');
  await page.getByRole('button', { name: 'Salvar processo', exact: true }).click();
  await expect(process).toContainText('Conferência revisada');
  await page.getByRole('button', { name: 'Associações', exact: true }).click();
  await page.getByLabel('Escolha um produto').selectOption({ label: 'BROWSER-CUBE · Cubo revisado' });
  await page.locator('#association-process').selectOption({ label: 'BROWSER-CHECK · Conferência revisada' });
  await page.getByRole('button', { name: 'Associar processo', exact: true }).click();
  await expect(page.locator('#association-rows')).toContainText('Conferência revisada');
  await page.reload();
  await expect(page.locator('#product-count')).not.toHaveText('—');
  await page.getByRole('button', { name: 'Associações', exact: true }).click();
  await page.getByLabel('Escolha um produto').selectOption({ label: 'BROWSER-CUBE · Cubo revisado' });
  await expect(page.locator('#association-rows')).toContainText('Conferência revisada');
  await page.getByRole('button', { name: 'Processos', exact: true }).click();
  await process.getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.locator('#notice')).toContainText('Remova as associações');
  await expect(process).toBeVisible();
  await page.getByRole('button', { name: 'Associações', exact: true }).click();
  await page.locator('#association-rows').getByRole('button', { name: 'Remover', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.locator('#association-rows li')).toHaveCount(0);
  await page.getByRole('button', { name: 'Produtos', exact: true }).click();
  await product.getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(product).toHaveCount(0);
  await page.getByRole('button', { name: 'Processos', exact: true }).click();
  await process.getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(process).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('erros recuperáveis, busca, conteúdo seguro e layout desktop', async ({ page, request }) => {
  await request.post('/api/products', { data: { sku: 'SAFE-TEXT', name: '<img src=x onerror=alert(1)>' } });
  await page.goto('/');
  await expect(page.locator('#product-count')).not.toHaveText('—');
  await page.getByLabel('Buscar produtos').fill('SAFE-TEXT');
  await expect(page.locator('#product-rows tr')).toHaveCount(1);
  await expect(page.locator('#product-rows img')).toHaveCount(0);
  await page.getByLabel('Código SKU').fill('SAFE-TEXT');
  await page.getByLabel('Nome do produto').fill('Duplicado');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  await expect(page.locator('#notice')).toContainText('Já existe um produto com este SKU');
  await expect(page.getByLabel('Nome do produto')).toHaveValue('Duplicado');
  await page.getByLabel('Buscar produtos').fill('nenhum resultado');
  await expect(page.locator('#product-empty')).toBeVisible();
  await page.getByLabel('Buscar produtos').fill('');
  await page.getByLabel('Código SKU').fill(''); await page.getByLabel('Nome do produto').fill('');
  await page.getByRole('button', { name: 'Atualizar', exact: false }).click();
  await expect(page.locator('#notice')).toContainText('Catálogo atualizado');
  await page.setViewportSize({ width: 1440, height: 1000 });
  fs.mkdirSync('.entrega', { recursive: true });
  await page.screenshot({ path: '.entrega/frontend-desktop.png', fullPage: true });
});
test('layout mobile e falha de rede exibida sem perder o formulário', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('#product-count')).not.toHaveText('—');
  await expect(page.getByLabel('Nome do produto')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '.entrega/frontend-mobile.png', fullPage: true });
  await page.route('**/api/products', route => route.abort());
  await page.getByLabel('Código SKU').fill('NETWORK-ERROR');
  await page.getByLabel('Nome do produto').fill('Preservar formulário');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  await expect(page.locator('#notice')).toContainText('Não foi possível conectar');
  await expect(page.getByLabel('Nome do produto')).toHaveValue('Preservar formulário');
});
